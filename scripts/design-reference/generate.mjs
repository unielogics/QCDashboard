// Runs the Earnings Plan design's own arithmetic and writes the numbers every
// implementation of the plan engine (Python and TypeScript) must reproduce.
//
//   node scripts/design-reference/generate.mjs
//
// The design logic file is the exported Claude Design script, unedited. It is
// evaluated in an empty VM context: it only computes, it has no I/O.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const logic = readFileSync(join(here, "earnings-plan-v2.logic.js"), "utf8");

// The design keeps its working figures in locals; expose them just before it
// formats them for display.
const hook = `
    this.__dbg = {
      IRS, G, target, e0, noi0, ds, rate,
      model: { volume: S0.vol, revenue: S0.rev, total: S0.tot },
      items: items.map(i => ({ id: i.id, kind: i.kind, area: i.area, start: startOf(i.id), included: P(i.id), reviewed: R(i.id) })),
      proposed: { revenue: EP.rev, cogs: EP.cogs, opex: EP.opex, noi: EP.noi, ebitda: EP.e, activity_spend: EP.extra, lines: EP.amt, stream_revenue: EP.st.rev, stream_volume: EP.st.vol, factors: EP.st.fv },
      reviewed: { revenue: ER.rev, cogs: ER.cogs, opex: ER.opex, noi: ER.noi, ebitda: ER.e, activity_spend: ER.extra, lines: ER.amt, stream_revenue: ER.st.rev, stream_volume: ER.st.vol, factors: ER.st.fv },
      months: { proposed: MP.map(m => ({ ebitda: m.e, noi: m.noi })), reviewed: MR.map(m => ({ ebitda: m.e, noi: m.noi })) },
      first_year: { proposed: { ebitda: FP.e, noi: FP.noi }, reviewed: { ebitda: FR.e, noi: FR.noi } },
      effects: Object.fromEntries(items.map(i => { const st = stat(i.id), s0 = startOf(i.id), one = i.c.setupCad === 'mo' ? 0 : n(i.c.setup); return [i.id, { ebitda: st.d, revenue: st.dRev, first_year: st.d * (13 - s0) / 12 - one }]; })),
      sections: [[0, 1], [2], [3], [4], [5]].map(areas => EP.e - ev(q => P(q) && !areas.includes(areaOf(q))).e),
      bridge: wsteps.map(([label, value]) => ({ label, value })),
      to_finish: iss.map(i => ({ label: i.label, step: i.step })),
      released: { available_monthly: cap, allocated_monthly: allocated },
      goal: { amount: goal, gap },
    };
`;
const marker = /\n(\s*)return \{\s*\n\s*viewerChip:/;
if (!marker.test(logic)) throw new Error("The design logic changed shape: the display block was not found.");
const source = logic.replace(marker, match => hook + match);

function run(props, patch = {}) {
  const sandbox = { __props: props, __patch: patch, __out: null };
  sandbox.DCLogic = class { constructor() { this.props = sandbox.__props; } setState() {} };
  vm.createContext(sandbox);
  vm.runInContext(`${source}\nconst c = new Component(); Object.assign(c.state, __patch); const view = c.renderVals(); __out = { state: c.state, view, dbg: c.__dbg };`, sandbox, { timeout: 10_000 });
  return sandbox.__out;
}

const round = value => JSON.parse(JSON.stringify(value, (_key, v) => typeof v === "number" ? Math.round(v * 1e6) / 1e6 : v));
const staff = { dscrTarget: 1.25, applyLoanTerms: true, viewer: "Staff" };
const base = run(staff);
const reviewedView = run(staff, { view: "reviewed" });
const currentDebt = run({ ...staff, applyLoanTerms: false });
const metrics = result => result.view.metrics.map(m => ({ label: m.label, before: m.b, after: m.a }));
const scenario = (result, view, applyLoanTerms) => ({
  view, apply_loan_terms: applyLoanTerms, annual_debt_service: result.dbg.ds,
  metrics: metrics(result), bridge: result.dbg.bridge, released: result.dbg.released,
});

const { state, dbg } = base;
const fixture = {
  about: "Reference numbers from the Earnings Plan v2 design. Generated by scripts/design-reference/generate.mjs; do not edit by hand.",
  baseline: {
    revenue: dbg.IRS.rev, cogs: dbg.IRS.cogs, operating_expenses: dbg.IRS.opex, other_income: dbg.IRS.other,
    noi: dbg.noi0, ebitda: dbg.e0, debt_service_current: dbg.IRS.dsCur, debt_service_with_terms: dbg.IRS.dsNew,
    groups: dbg.G.map(g => ({ key: g.k, label: g.l, return_amount: g.irs, statement_amount: g.pl })),
  },
  target_dscr: dbg.target,
  plan: {
    plan_start: state.planStart, noi_goal: Number(state.goal),
    streams: state.streams, lines: state.lines, changes: state.chg, growth: state.growth, activities: state.acts,
    allocations: state.alloc, confirmations: state.confirm,
  },
  expected: {
    model: dbg.model, rates: dbg.rate, items: dbg.items,
    proposed: dbg.proposed, reviewed: dbg.reviewed, months: dbg.months, first_year: dbg.first_year,
    effects: dbg.effects, sections: dbg.sections, to_finish: dbg.to_finish, goal: dbg.goal,
  },
  scenarios: {
    proposed_with_terms: scenario(base, "proposed", true),
    reviewed_with_terms: scenario(reviewedView, "reviewed", true),
    proposed_current_debt: scenario(currentDebt, "proposed", false),
  },
};

const target = join(here, "..", "..", "src", "lib", "__tests__", "fixtures", "earningsPlanReference.json");
writeFileSync(target, JSON.stringify(round(fixture), null, 1) + "\n");
const first = fixture.scenarios.proposed_with_terms.metrics;
console.log(`Wrote ${target}`);
console.log(first.map(m => `${m.label}: ${Math.round(m.before * 100) / 100} -> ${Math.round(m.after * 100) / 100}`).join(" | "));
